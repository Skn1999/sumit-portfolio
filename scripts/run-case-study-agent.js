import fs from 'fs';
import path from 'path';

async function run() {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    console.error("❌ Error: GEMINI_API_KEY environment variable is required.");
    process.exit(1);
  }

  const taskFilePath = process.argv[2];
  if (!taskFilePath || !fs.existsSync(taskFilePath)) {
    console.error(`❌ Error: Task file not found at path: ${taskFilePath}`);
    process.exit(1);
  }

  console.log(`📖 Processing task file: ${taskFilePath}`);

  // Load context files
  const agentSpec = fs.readFileSync('.agent/case-study-rewriter-agent.md', 'utf8');
  const framework = fs.readFileSync('.agent/benchmark-framework.md', 'utf8');
  const uiInstructions = fs.readFileSync('.agent/ui-building-instructions.md', 'utf8');
  const taskContent = fs.readFileSync(taskFilePath, 'utf8');

  // Load target project reference content if available
  const ediaqiRestructurePath = 'src/content/projects/ediaqi-decision-support-system/restructure.md';
  let restructureContent = '';
  if (fs.existsSync(ediaqiRestructurePath)) {
    restructureContent = fs.readFileSync(ediaqiRestructurePath, 'utf8');
  }

  const targetMdxPath = 'src/content/projects/ediaqi-decision-support-system/index.mdx';
  let currentMdx = '';
  if (fs.existsSync(targetMdxPath)) {
    currentMdx = fs.readFileSync(targetMdxPath, 'utf8');
  }

  const prompt = `
You are an expert Senior Product Designer and Case Study Writer executing an automated rewrite task.

=== AGENT ROLE & MISSION ===
${agentSpec}

=== STORYTELLING FRAMEWORK ===
${framework}

=== PORTFOLIO UI & DESIGN LANGUAGE INSTRUCTIONS ===
${uiInstructions}

=== SPECIFIC TASK REQUIREMENTS ===
${taskContent}

=== REFERENCE RESTRUCTURE MATERIAL ===
${restructureContent}

=== EXISTING MDX FILE ===
${currentMdx}

=== EXECUTION INSTRUCTIONS ===
Using all the context above, rewrite and generate the complete \`index.mdx\` file for this case study.

CRITICAL MDX SYNTAX SAFETY RULES (MUST FOLLOW TO PREVENT BUILD ERRORS):
1. **NO UNESCAPED CURLY BRACES IN PROSE**: MDX interprets \`{\` and \`}\` as JavaScript expressions!
   - BAD: "Study (N=200) tested {Cell A} and {Cell B}"
   - GOOD: "Study (N=200) tested Cell A and Cell B"
   - BAD: "{CO2 < 800 ppm}"
   - GOOD: "(CO2 < 800 ppm)" or \`CO2 < 800 ppm\`
2. **NO UNESCAPED ANGLE BRACKETS IN PROSE**: MDX interprets \`<word>\` as JSX tags!
   - BAD: "<2-Touchpoint Architecture>"
   - GOOD: "2-Touchpoint Architecture"
3. **VALID JSX COMPONENTS ONLY**:
   - Use \`<ProjectImageAsset src="..." alt="..." />\` for images.
   - Do NOT use unclosed HTML tags or raw JSX expressions.
4. **SECTION HEADERS**: Enforce the 6 universal section headers:
   \`## 01 // THE CHALLENGE\`
   \`## 02 // MY ROLE\`
   \`## 03 // WHAT WORKED vs. WHAT DIDN'T\`
   \`## 04 // THE SOLUTION\`
   \`## 05 // KEY INSIGHTS\`
   \`## 06 // IMPACT & LESSONS\`
5. **FRONTMATTER**: Preserve the exact YAML frontmatter at the top of the file (between \`---\` and \`---\`).

Return ONLY the exact raw MDX content with frontmatter. Do not wrap the output in markdown code blocks.
`;

  console.log("🤖 Requesting case study generation from Gemini API...");

  const response = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 0.2
      }
    })
  });

  const data = await response.json();
  if (data.error) {
    console.error("❌ Gemini API Error:", data.error);
    process.exit(1);
  }

  const generatedText = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!generatedText) {
    console.error("❌ No text response generated by Gemini API.");
    process.exit(1);
  }

  // Strip accidental wrapping markdown code block ticks if present
  let cleanedMdx = generatedText.trim();
  if (cleanedMdx.startsWith('```mdx')) {
    cleanedMdx = cleanedMdx.replace(/^```mdx\n/, '').replace(/\n```$/, '');
  } else if (cleanedMdx.startsWith('```markdown')) {
    cleanedMdx = cleanedMdx.replace(/^```markdown\n/, '').replace(/\n```$/, '');
  } else if (cleanedMdx.startsWith('```')) {
    cleanedMdx = cleanedMdx.replace(/^```\n/, '').replace(/\n```$/, '');
  }

  // Sanitize any remaining unescaped curly braces in prose (outside frontmatter and JSX props)
  cleanedMdx = cleanedMdx.split('\n').map(line => {
    if (line.trim().startsWith('import ') || line.trim().startsWith('<') || line.trim().startsWith('---')) {
      return line;
    }
    // Replace unescaped {text} in plain prose if it's not a JSX prop
    return line.replace(/\{([^}]+)\}/g, (match, p1) => {
      if (line.includes('={"') || line.includes('={')) return match;
      return p1; // strip the curly braces
    });
  }).join('\n');

  // Write updated MDX file
  fs.writeFileSync(targetMdxPath, cleanedMdx, 'utf8');
  console.log(`✅ Successfully updated ${targetMdxPath}`);

  // Append progress log to .agent/progress.md
  const dateStr = new Date().toISOString().split('T')[0];
  const progressEntry = `\n## [${dateStr}] Automated Task: ${path.basename(taskFilePath)}\n- **Status**: Completed\n- **Target File**: ${targetMdxPath}\n- **Framework**: Recruiter Benchmark Framework (Universal 6-Section Set)\n- **UI Rules**: Applied portfolio UI presentation guidelines\n`;
  fs.appendFileSync('.agent/progress.md', progressEntry, 'utf8');
  console.log('✅ Appended progress entry to .agent/progress.md');
}

run().catch((err) => {
  console.error("❌ Fatal Error running agent script:", err);
  process.exit(1);
});
